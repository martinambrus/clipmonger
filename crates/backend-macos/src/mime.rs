//! Canonical MIME <-> pasteboard type mapping (pure, T-801).
//!
//! The type names come from `AppKit` / `CoreServices` constants at runtime
//! ([`TypeNames`]); nothing here hardcodes a UTI except the nspasteboard.org
//! markers, which have no constants.

use clipmonger_platform::types::{Error, Result};

/// Canonical UTF-8 text.
pub const TEXT: &str = "text/plain;charset=utf-8";
/// Canonical HTML.
pub const HTML: &str = "text/html";
/// Canonical RTF.
pub const RTF: &str = "text/rtf";
/// Canonical image (PNG, normalized from TIFF when needed).
pub const PNG: &str = "image/png";
/// Canonical file list.
pub const URI_LIST: &str = "text/uri-list";
/// Prefix of passthrough formats (`x-os/<uti>`).
pub const PASSTHROUGH: &str = "x-os/";

/// Password managers: never store (nspasteboard.org).
pub const CONCEALED: &str = "org.nspasteboard.ConcealedType";
/// Short-lived content: never store (nspasteboard.org).
pub const TRANSIENT: &str = "org.nspasteboard.TransientType";
/// Machine-generated content: never store (nspasteboard.org).
pub const AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";

/// One raw pasteboard item: `(type, bytes)` pairs.
pub type Item = Vec<(String, Vec<u8>)>;

/// Pasteboard type names resolved from the OS constants.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TypeNames {
    /// `NSPasteboardTypeString`.
    pub string: String,
    /// `kUTTypeUTF16PlainText`.
    pub utf16: String,
    /// `NSPasteboardTypeHTML`.
    pub html: String,
    /// `NSPasteboardTypeRTF`.
    pub rtf: String,
    /// `NSPasteboardTypePNG`.
    pub png: String,
    /// `NSPasteboardTypeTIFF`.
    pub tiff: String,
    /// `kUTTypeFileURL`.
    pub file_url: String,
}

/// Whether the pasteboard types carry a never-store marker.
#[must_use]
pub fn is_sensitive(types: &[String]) -> bool {
    types
        .iter()
        .any(|t| t == CONCEALED || t == TRANSIENT || t == AUTO_GENERATED)
}

/// Canonical formats offered by a pasteboard with these types, in a stable
/// order: text, html, rtf, png, uri-list, then passthrough.
#[must_use]
pub fn offers_for(types: &[String], names: &TypeNames) -> Vec<String> {
    let has = |name: &str| types.iter().any(|t| t == name);
    let mut out = Vec::new();
    if has(&names.string) || has(&names.utf16) {
        out.push(TEXT.to_string());
    }
    if has(&names.html) {
        out.push(HTML.to_string());
    }
    if has(&names.rtf) {
        out.push(RTF.to_string());
    }
    if has(&names.png) || has(&names.tiff) {
        out.push(PNG.to_string());
    }
    if has(&names.file_url) {
        out.push(URI_LIST.to_string());
    }
    for t in types {
        if is_passthrough(t, names) {
            let mime = format!("{PASSTHROUGH}{t}");
            if !out.contains(&mime) {
                out.push(mime);
            }
        }
    }
    out
}

/// Whether a pasteboard type is kept as `x-os/<uti>`: a real UTI that no
/// canonical format covers. Legacy names (`NSStringPboardType`, `NeXT ...`),
/// dynamic `dyn.` types, text variants and the markers are dropped.
#[must_use]
pub fn is_passthrough(t: &str, names: &TypeNames) -> bool {
    let mapped = [
        &names.string,
        &names.utf16,
        &names.html,
        &names.rtf,
        &names.png,
        &names.tiff,
        &names.file_url,
    ];
    !t.is_empty()
        && !mapped.iter().any(|m| m.as_str() == t)
        && t.contains('.')
        && !t.contains(char::is_whitespace)
        && !t.starts_with("dyn.")
        && !t.ends_with("plain-text")
        && t != CONCEALED
        && t != TRANSIENT
        && t != AUTO_GENERATED
}

/// Native write plan for one payload map.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct WritePlan {
    /// `(type, bytes)` set on the first pasteboard item.
    pub data: Vec<(String, Vec<u8>)>,
    /// `file://` URLs written as `NSURL` objects.
    pub file_urls: Vec<String>,
}

/// Map a canonical payload to native types. `png_to_tiff` adds the TIFF
/// copy older apps read; text goes out as UTF-8 plus BOM-less UTF-16.
///
/// # Errors
///
/// [`Error::Unsupported`] when no payload entry maps to a pasteboard type.
pub fn plan_write(
    payload: &[(String, Vec<u8>)],
    names: &TypeNames,
    png_to_tiff: impl Fn(&[u8]) -> Option<Vec<u8>>,
) -> Result<WritePlan> {
    let mut plan = WritePlan::default();
    let push = |plan: &mut WritePlan, uti: &str, bytes: Vec<u8>| {
        if !plan.data.iter().any(|(t, _)| t == uti) {
            plan.data.push((uti.to_string(), bytes));
        }
    };
    for (mime, bytes) in payload {
        match canonical_kind(mime) {
            Some(Kind::Text) => {
                let text = String::from_utf8_lossy(bytes);
                push(&mut plan, &names.string, text.as_bytes().to_vec());
                push(&mut plan, &names.utf16, crate::text::utf16_no_bom(&text));
            }
            Some(Kind::Html) => push(&mut plan, &names.html, bytes.clone()),
            Some(Kind::Rtf) => push(&mut plan, &names.rtf, bytes.clone()),
            Some(Kind::Png) => {
                push(&mut plan, &names.png, bytes.clone());
                if let Some(tiff) = png_to_tiff(bytes) {
                    push(&mut plan, &names.tiff, tiff);
                }
            }
            Some(Kind::UriList) => {
                let text = String::from_utf8_lossy(bytes);
                for url in crate::uri::file_uris(&text) {
                    if !plan.file_urls.contains(&url) {
                        plan.file_urls.push(url);
                    }
                }
            }
            Some(Kind::Passthrough(uti)) if !uti.is_empty() => {
                push(&mut plan, uti, bytes.clone());
            }
            Some(Kind::Passthrough(_)) | None => {}
        }
    }
    if plan.data.is_empty() && plan.file_urls.is_empty() {
        return Err(Error::Unsupported(
            "no payload format maps to a pasteboard type".to_string(),
        ));
    }
    Ok(plan)
}

/// Canonical format kind.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind<'a> {
    /// UTF-8 text.
    Text,
    /// HTML.
    Html,
    /// RTF.
    Rtf,
    /// PNG image.
    Png,
    /// File list.
    UriList,
    /// `x-os/<uti>` with the UTI.
    Passthrough(&'a str),
}

/// Classify a canonical MIME name.
#[must_use]
pub fn canonical_kind(mime: &str) -> Option<Kind<'_>> {
    if let Some(uti) = mime.strip_prefix(PASSTHROUGH) {
        return Some(Kind::Passthrough(uti));
    }
    match mime.to_ascii_lowercase().replace(' ', "").as_str() {
        "text/plain;charset=utf-8" | "text/plain" | "utf8_string" => Some(Kind::Text),
        "text/html" => Some(Kind::Html),
        "text/rtf" | "application/rtf" => Some(Kind::Rtf),
        "image/png" => Some(Kind::Png),
        "text/uri-list" => Some(Kind::UriList),
        _ => None,
    }
}

/// Canonical view of raw pasteboard items (what a capture would read),
/// for registering the restore write. `tiff_to_png` normalizes images.
#[must_use]
pub fn canonical_items(
    items: &[Item],
    names: &TypeNames,
    tiff_to_png: impl Fn(&[u8]) -> Option<Vec<u8>>,
) -> Vec<(String, Vec<u8>)> {
    let first = |t: &str| {
        items
            .iter()
            .flat_map(|item| item.iter())
            .find(|(name, _)| name == t)
            .map(|(_, bytes)| bytes.clone())
    };
    let mut out = Vec::new();
    if let Some(text) = first(&names.string).or_else(|| {
        first(&names.utf16).map(|units| crate::text::utf16_to_utf8(&units).into_bytes())
    }) {
        out.push((TEXT.to_string(), text));
    }
    if let Some(html) = first(&names.html) {
        out.push((HTML.to_string(), html));
    }
    if let Some(rtf) = first(&names.rtf) {
        out.push((RTF.to_string(), rtf));
    }
    if let Some(png) =
        first(&names.png).or_else(|| first(&names.tiff).and_then(|t| tiff_to_png(&t)))
    {
        out.push((PNG.to_string(), png));
    }
    let urls: Vec<String> = items
        .iter()
        .flat_map(|item| item.iter())
        .filter(|(name, _)| name == &names.file_url)
        .map(|(_, bytes)| String::from_utf8_lossy(bytes).trim().to_string())
        .filter(|url| url.starts_with("file://"))
        .collect();
    if !urls.is_empty() {
        out.push((URI_LIST.to_string(), crate::uri::join(&urls).into_bytes()));
    }
    for item in items {
        for (name, bytes) in item {
            if is_passthrough(name, names) {
                let mime = format!("{PASSTHROUGH}{name}");
                if !out.iter().any(|(m, _)| m == &mime) {
                    out.push((mime, bytes.clone()));
                }
            }
        }
    }
    out
}

#[cfg(test)]
pub(crate) fn test_names() -> TypeNames {
    // UTI values behind the AppKit constants (seg-08 §10.1, test data only).
    TypeNames {
        string: "public.utf8-plain-text".into(),
        utf16: "public.utf16-plain-text".into(),
        html: "public.html".into(),
        rtf: "public.rtf".into(),
        png: "public.png".into(),
        tiff: "public.tiff".into(),
        file_url: "public.file-url".into(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn types(list: &[&str]) -> Vec<String> {
        list.iter().map(|s| (*s).to_string()).collect()
    }

    #[test]
    fn t801_offers_map_constants_and_passthrough() {
        let names = test_names();
        let offered = offers_for(
            &types(&[
                "public.utf8-plain-text",
                "public.utf16-plain-text",
                "NSStringPboardType",
                "public.html",
                "public.rtf",
                "public.tiff",
                "NeXT TIFF v4.0 pasteboard type",
                "public.file-url",
                "public.url",
                "com.apple.flat-rtfd",
                "dyn.ah62d4rv4gu8y",
                "com.apple.traditional-mac-plain-text",
            ]),
            &names,
        );
        assert_eq!(
            offered,
            [
                TEXT,
                HTML,
                RTF,
                PNG,
                URI_LIST,
                "x-os/public.url",
                "x-os/com.apple.flat-rtfd"
            ]
        );
        assert_eq!(
            offers_for(&types(&["public.png"]), &names),
            [PNG],
            "PNG alone is image/png"
        );
        assert_eq!(offers_for(&[], &names), Vec::<String>::new());
    }

    #[test]
    fn markers_are_sensitive_and_never_passthrough() {
        let names = test_names();
        for marker in [CONCEALED, TRANSIENT, AUTO_GENERATED] {
            let list = types(&["public.utf8-plain-text", marker]);
            assert!(is_sensitive(&list));
            assert_eq!(offers_for(&list, &names), [TEXT]);
        }
        assert!(!is_sensitive(&types(&["public.utf8-plain-text"])));
    }

    #[test]
    fn write_plan_covers_every_canonical_format() {
        let names = test_names();
        let payload = vec![
            (TEXT.to_string(), "héllo".as_bytes().to_vec()),
            (HTML.to_string(), b"<b>x</b>".to_vec()),
            (RTF.to_string(), b"{\\rtf1 x}".to_vec()),
            (PNG.to_string(), vec![0x89, b'P']),
            (
                URI_LIST.to_string(),
                b"# c\r\nfile:///Users/a/x%20y.txt\r\nhttps://e.com/\r\n".to_vec(),
            ),
            ("x-os/com.example.custom".to_string(), vec![7]),
            ("application/x-unknown".to_string(), vec![1]),
        ];
        let plan = plan_write(&payload, &names, |_| Some(vec![b'I', b'I'])).unwrap();
        let utis: Vec<&str> = plan.data.iter().map(|(t, _)| t.as_str()).collect();
        assert_eq!(
            utis,
            [
                "public.utf8-plain-text",
                "public.utf16-plain-text",
                "public.html",
                "public.rtf",
                "public.png",
                "public.tiff",
                "com.example.custom"
            ]
        );
        assert_eq!(plan.data[0].1, "héllo".as_bytes());
        assert_eq!(plan.data[1].1, crate::text::utf16_no_bom("héllo"));
        assert_eq!(plan.file_urls, ["file:///Users/a/x%20y.txt"]);
        assert!(matches!(
            plan_write(&[("application/x-unknown".into(), vec![])], &names, |_| {
                None
            }),
            Err(Error::Unsupported(_))
        ));
    }

    #[test]
    fn canonical_items_match_capture_view() {
        let names = test_names();
        let items = vec![
            vec![
                (
                    "public.utf16-plain-text".to_string(),
                    crate::text::utf16_no_bom("hi"),
                ),
                ("public.tiff".to_string(), vec![1, 2]),
                ("com.example.custom".to_string(), vec![9]),
            ],
            vec![("public.file-url".to_string(), b"file:///a".to_vec())],
            vec![("public.file-url".to_string(), b"file:///b".to_vec())],
        ];
        let view = canonical_items(&items, &names, |_| Some(vec![0x89]));
        assert_eq!(
            view,
            vec![
                (TEXT.to_string(), b"hi".to_vec()),
                (PNG.to_string(), vec![0x89]),
                (URI_LIST.to_string(), b"file:///a\r\nfile:///b".to_vec()),
                ("x-os/com.example.custom".to_string(), vec![9]),
            ]
        );
    }

    #[test]
    fn canonical_kind_names() {
        assert_eq!(
            canonical_kind("text/plain; charset=UTF-8"),
            Some(Kind::Text)
        );
        assert_eq!(
            canonical_kind("x-os/public.url"),
            Some(Kind::Passthrough("public.url"))
        );
        assert_eq!(canonical_kind("image/jpeg"), None);
    }
}
